// Regenerates src/crypto-exchanges.ts from the installed CCXT version.
//   node packages/brokers/scripts/gen-crypto-exchanges.mjs
import { writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const ccxt = require("ccxt");
const here = dirname(fileURLToPath(import.meta.url));

// Best-effort, from public reports (Sept 2026). ALWAYS verify on https://fiuindia.gov.in
const INDIA = {
  binance: ["FIU_REGISTERED_REPORTED", "Registered with FIU-IND after 2024 penalty (verify)"],
  kucoin: ["FIU_REGISTERED_REPORTED", "Registered with FIU-IND (verify)"],
  kucoinfutures: ["FIU_REGISTERED_REPORTED", "KuCoin futures (verify availability for India)"],
  bybit: ["FIU_REGISTERED_REPORTED", "Registered with FIU-IND in 2025 (verify)"],
  coinbase: ["FIU_REGISTERED_REPORTED", "Registered with FIU-IND (verify)"],
  bitget: ["FIU_REGISTERED_REPORTED", "Registered with FIU-IND (verify)"],
  zebpay: ["INDIAN_EXCHANGE", "Indian exchange, INR pairs"],
  mudrex: ["INDIAN_EXCHANGE", "Indian platform, INR (API keys needed even for market data)"],
  bitbns: ["INDIAN_EXCHANGE", "Indian exchange, INR pairs (no historical candles via API)"],
  delta: [
    "INDIAN_EXCHANGE",
    "Delta Exchange; the India entity offers INR-settled derivatives (verify endpoint)",
  ],
  okx: ["EXITED_INDIA", "Reported to have exited India instead of registering"],
  binanceus: ["REGION_LOCKED", "US-only"],
  okxus: ["REGION_LOCKED", "US-only"],
  bybiteu: ["REGION_LOCKED", "EU-only"],
  bybitid: ["REGION_LOCKED", "Indonesia-only"],
  gateeu: ["REGION_LOCKED", "EU-only"],
  coinbaseinternational: ["REGION_LOCKED", "International / institutional"],
};

const rows = ccxt.exchanges.map((id) => {
  const e = new ccxt[id]();
  const [india, note] = INDIA[id] ?? ["NOT_VERIFIED_FOR_INDIA", ""];
  return {
    id,
    name: e.name,
    countries: (e.countries ?? []).slice(0, 3),
    websocket: Boolean(ccxt.pro && ccxt.pro[id]),
    spot: Boolean(e.has.spot),
    perp: Boolean(e.has.swap),
    certified: Boolean(e.certified),
    ohlcv: Boolean(e.has.fetchOHLCV),
    india,
    ...(note ? { note } : {}),
  };
});

const notInCcxt = [
  ["coindcx", "CoinDCX", true, "FIU-registered Indian exchange; custom adapter needed"],
  ["wazirx", "WazirX", false, "Indian exchange; custom adapter needed"],
  ["coinswitch", "CoinSwitch", false, "FIU-registered Indian platform; custom adapter needed"],
  ["giottus", "Giottus", false, "Indian exchange; custom adapter needed"],
].map(([id, name, perp, note]) => ({
  id,
  name,
  countries: ["IN"],
  websocket: false,
  spot: true,
  perp,
  certified: false,
  ohlcv: false,
  india: "NOT_IN_CCXT",
  note,
  supported: false,
}));

const out = `// GENERATED by scripts/gen-crypto-exchanges.mjs from ccxt ${ccxt.version}. Edit INDIA flags in the script, not here.
// India flags are best-effort from public reports — ALWAYS verify on https://fiuindia.gov.in before trading.

export type IndiaStatus =
  | "FIU_REGISTERED_REPORTED"
  | "INDIAN_EXCHANGE"
  | "EXITED_INDIA"
  | "REGION_LOCKED"
  | "NOT_VERIFIED_FOR_INDIA"
  | "NOT_IN_CCXT";

export interface CryptoExchangeInfo {
  id: string; // CCXT exchange id, used as Instrument.venue
  name: string;
  countries: string[];
  websocket: boolean; // CCXT Pro streaming available
  spot: boolean;
  perp: boolean;
  certified: boolean; // CCXT "certified" integration
  ohlcv: boolean; // historical candles via API (needed for backtests / warm-up)
  india: IndiaStatus;
  note?: string;
  supported?: boolean; // false = listed for reference only (no adapter yet)
}

export const CCXT_VERSION = ${JSON.stringify(ccxt.version)};

export const CRYPTO_EXCHANGES: readonly CryptoExchangeInfo[] = ${JSON.stringify([...rows, ...notInCcxt], null, 2)};

export const isSupportedCryptoExchange = (id: string): boolean =>
  CRYPTO_EXCHANGES.some((e) => e.id === id && e.supported !== false);
`;

writeFileSync(join(here, "..", "src", "crypto-exchanges.ts"), out);
console.info(
  `wrote ${rows.length} CCXT exchanges + ${notInCcxt.length} Indian exchanges without CCXT support`,
);
